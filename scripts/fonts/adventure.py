ALIASES = {'‘':"'",'’':"'",'‚':',','“':'"','”':'"','„':'"','−':'–','‹':'<','›':'>',' ':' '}
ACCENTS = {'\u0300':['100','010'], '\u0301':['001','010'], '\u0302':['010','101'], '\u0303':['0101','1010'], '\u0308':['101'], '\u030a':['010','101','010'], '\u0304':['111'], '\u0306':['101','010'], '\u0307':['1'], '\u030b':['0101','1010'], '\u030c':['101','010']}


def drawing(ch):
    ch = ALIASES.get(ch, ch)
    if ch in PATTERNS:
        return PATTERNS[ch].split('/'), 7
    parts = unicodedata.normalize('NFD', ch)
    if len(parts) > 1 and parts[0] in PATTERNS:
        rows = PATTERNS[parts[0]].split('/')
        mark = ACCENTS.get(parts[1])
        if mark:
            width = max(len(rows[0]), len(mark[0]))
            pad = lambda row: row.center(width, '0')
            return [*(pad(r) for r in mark), '0'*width, *(pad(r) for r in rows)], 8 + len(mark)
        if parts[1] == '\u0327':
            return rows + ['00100', '01000'], 7
    return None


for name, cap, xscale, tracking, line in [('regular',12,2,1,19),('small',8,1,1,12),('tiny',7,1,1,10)]:
    out = ['// Original adventure reading face. Generated by scripts/fonts/adventure.py.',
           f'font {name}',f'cap {cap}',f'xheight {cap-3 if name=="regular" else cap}',
           f'ascent {cap+5}',f'descent {4 if name=="regular" else 2}',f'line {line}',
           f'tracking {tracking}','word 1',f'upper {0 if name=="regular" else 1}']
    chars = sorted(set(chr(c) for c in range(32,384)) | set(PATTERNS) | set(ALIASES))
    ascent = descent = 0
    for ch in chars:
        if ch in [' ', '\u00a0']:
            out += [f'glyph {ord(ch):04X} {4 if xscale==2 else 3} 0 0','']
            continue
        draw = drawing(ch)
        if not draw:
            continue
        rows, top = draw
        width = max(map(len, rows))
        rows = [row.center(width, '0') for row in rows]
        # Grid-fit rows with the baseline fixed at the requested cap height.
        expanded = []
        for i, row in enumerate(rows):
            source_y = i - top
            count = round((source_y+1)*cap/7) - round(source_y*cap/7)
            expanded += [''.join('#'*xscale if c=='1' else '.'*xscale for c in row)] * count
        top_px = round(top*cap/7)
        while expanded and '#' not in expanded[0]:
            expanded.pop(0)
            top_px -= 1
        while expanded and '#' not in expanded[-1]: expanded.pop()
        if not expanded: continue
        ascent = max(ascent, top_px)
        descent = max(descent, len(expanded) - top_px)
        width = len(expanded[0])
        out += [f'glyph {ord(ch):04X} {width+1} 0 {top_px}', *expanded, '']
    out[4] = f'ascent {ascent}'
    out[5] = f'descent {descent}'
    (ROOT / f'src/assets/fonts/adventure-{name}.txt').write_text('\n'.join(out).rstrip()+'\n')
